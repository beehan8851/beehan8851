# The iOS app's other ten languages, one JSON file each in tools/translations/.
# Add or fix a string there and run this again; a key missing there falls back to English.
LANGS = {"de": "de", "es": "es", "fr": "fr", "it": "it", "ja": "ja", "ko": "ko", "pt-BR": "pt-rBR",
         "tr": "tr", "zh-Hans": "b+zh+Hans", "zh-Hant": "b+zh+Hant"}
MANY = {"es", "fr", "it", "pt-BR"}  # CLDR gives these a "many" form for very large numbers


def write_translation(lang, qualifier):
    t = json.loads((pathlib.Path(__file__).resolve().parent / "translations" / f"{lang}.json").read_text(encoding="utf-8"))
    out = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Generated by tools/strings.py from tools/translations. Edit there. -->", "<resources>"]
    missing = [k for k in S if k != "app_name" and k not in t["strings"]]
    for k, v in S.items():
        if k == "app_name":
            continue
        out.append(f'    <string name="{k}">{text(t["strings"].get(k, v[0]))}</string>')
    for k, v in ARRAYS.items():
        items = t["arrays"].get(k, v[0])
        out.append(f'    <string-array name="{k}">')
        out += [f"        <item>{text(i)}</item>" for i in items]
        out.append("    </string-array>")
    for k, v in PLURALS.items():
        forms = t["plurals"].get(k, {"one": v[0][0], "other": v[0][1]})
        if lang in MANY and "one" in forms:
            forms = {**forms, "many": forms["other"]}
        out.append(f'    <plurals name="{k}">')
        out += [f'        <item quantity="{q}">{text(x)}</item>' for q, x in forms.items()]
        out.append("    </plurals>")
    out.append("</resources>")
    d = RES / f"values-{qualifier}"
    d.mkdir(parents=True, exist_ok=True)
    (d / "strings.xml").write_text("\n".join(out) + "\n")
    if missing:
        print(f"  {lang}: {len(missing)} strings fall back to English: {', '.join(missing[:8])}")


for lang, qualifier in LANGS.items():
    write_translation(lang, qualifier)
print(len(LANGS), "more languages from tools/translations")
