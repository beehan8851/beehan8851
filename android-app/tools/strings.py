def text(s):
    s = escape(s).replace("'", "\\'").replace('"', '\\"')
    return s


def write(folder, idx):
    out = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Generated by tools/strings.py. Edit there. -->", "<resources>"]
    for k, v in S.items():
        # The brand name stays as it is in every language.
        attr = ' translatable="false"' if k == "app_name" else ""
        if k == "app_name" and idx:
            continue
        out.append(f'    <string name="{k}"{attr}>{text(v[idx])}</string>')
    for k, v in ARRAYS.items():
        out.append(f'    <string-array name="{k}">')
        out += [f"        <item>{text(i)}</item>" for i in v[idx]]
        out.append("    </string-array>")
    for k, (en, uz, ru) in PLURALS.items():
        out.append(f'    <plurals name="{k}">')
        if idx == 0:
            out += [f'        <item quantity="one">{text(en[0])}</item>', f'        <item quantity="other">{text(en[1])}</item>']
        elif idx == 1:
            out += [f'        <item quantity="one">{text(uz)}</item>', f'        <item quantity="other">{text(uz)}</item>']
        else:
            out += [f'        <item quantity="one">{text(ru[0])}</item>', f'        <item quantity="few">{text(ru[1])}</item>',
                    f'        <item quantity="many">{text(ru[2])}</item>', f'        <item quantity="other">{text(ru[1])}</item>']
        out.append("    </plurals>")
    out.append("</resources>")
    d = RES / folder
    d.mkdir(parents=True, exist_ok=True)
    (d / "strings.xml").write_text("\n".join(out) + "\n")


